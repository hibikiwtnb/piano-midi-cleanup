def tr_report(text):
    """Translate report labels and known value phrases without changing the TXT."""
    text = text.strip()
    translated = tr(text)
    if translated != text:
        return translated
    hands = text.split(', ')
    if len(hands) > 1 and all(hand in (
        'left', 'right', 'second left', 'second right',
        'left hand', 'right hand', 'second left hand', 'second right hand',
    ) for hand in hands):
        return tr(', ').join(tr(hand) for hand in hands)
    for pattern, template in _REPORT_PATTERNS:
        match = re.fullmatch(pattern, text)
        if match:
            return tr(template).format(*(tr_report(value) for value in match.groups()))
    return text
